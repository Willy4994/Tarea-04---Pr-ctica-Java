public class TiposPrimitivos {
    public static void main(String[] args) {
        int entero = 1024;
        long largo = 1000000000000L;
        short corto = 120;
        byte pequeno = 10;
        float realFloat = 1.0f;
        double realDouble = 3.14159;
        char caracter = 'A';
        boolean logico = true;
        String texto = "Hola, Java";

        System.out.println("int: " + entero);
        System.out.println("long: " + largo);
        System.out.println("short: " + corto);
        System.out.println("byte: " + pequeno);
        System.out.println("float: " + realFloat);
        System.out.println("double: " + realDouble);
        System.out.println("char: " + caracter);
        System.out.println("boolean: " + logico);
        System.out.println("String: " + texto);
    }
}
