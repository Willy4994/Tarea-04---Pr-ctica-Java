public class Declaraciones {
    public static void main(String[] args) {
        int i = 1;
        double pi = 3.14159;
        char c = 'a';
        boolean estamosBien = true;

        System.out.println("i = " + i);
        System.out.println("pi = " + pi);
        System.out.println("c = " + c);
        System.out.println("Estamos bien: " + estamosBien);
    }
}
